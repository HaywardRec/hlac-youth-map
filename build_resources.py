"""
Builds resources.js -- the "Mental Health & Support" and "Youth Programs" map layers --
from youth_resources.csv, a hand-kept list you can edit in Excel.

To add or fix a place: edit youth_resources.csv (one row per place; `layer` is `support`
or `youth`), then run `python build_resources.py` and push. Addresses are geocoded once
through OpenStreetMap Nominatim and cached in resources_geocode_cache.json. To pin a
place by hand, add its "lon,lat" to the cache file under its exact address.

The `verified` column records when a row was last checked (YYYY-MM). Phone numbers and
hours change, so it's worth re-checking rows older than a year.
"""
import csv
import json
import os

import build_events as be

HERE = os.path.dirname(os.path.abspath(__file__))
CSV_PATH = os.path.join(HERE, "youth_resources.csv")
OUT_PATH = os.path.join(HERE, "resources.js")
CACHE_PATH = os.path.join(HERE, "resources_geocode_cache.json")

FIELDS = ["name", "type", "address", "phone", "ages", "cost", "description", "website", "verified"]


def main():
    cache = json.load(open(CACHE_PATH, encoding="utf-8")) if os.path.exists(CACHE_PATH) else {}
    layers = {"support": [], "youth": []}
    missing = []
    with open(CSV_PATH, encoding="utf-8-sig", newline="") as f:
        for row in csv.DictReader(f):
            layer = row["layer"].strip()
            if layer not in layers or not row["name"].strip():
                continue
            coords = be.geocode(row["address"].strip(), cache)
            if not coords:
                missing.append(f"{row['name']} -- {row['address']}")
                continue
            props = {k: row.get(k, "").strip() for k in FIELDS}
            props["source"] = "Support" if layer == "support" else "Youth"
            layers[layer].append({"type": "Feature",
                                  "geometry": {"type": "Point", "coordinates": coords},
                                  "properties": props})
    with open(OUT_PATH, "w", encoding="utf-8") as f:
        f.write("// Generated by build_resources.py from youth_resources.csv -- edit the CSV, not this file.\n")
        f.write("const RESOURCES_DATA = ")
        json.dump({k: {"type": "FeatureCollection", "features": v} for k, v in layers.items()}, f, ensure_ascii=False)
        f.write(";\n")
    with open(CACHE_PATH, "w", encoding="utf-8") as f:
        json.dump(cache, f, indent=1, sort_keys=True)
    for k, v in layers.items():
        print(f"{k}: {len(v)} places")
        for ft in v:
            lon, lat = ft["geometry"]["coordinates"]
            print(f"   {lat:.5f},{lon:.5f}  {ft['properties']['name']}")
    if missing:
        print("Could not geocode (add 'lon,lat' to the cache by hand):")
        for m in missing:
            print("  -", m)


if __name__ == "__main__":
    main()
